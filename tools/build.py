#!/usr/bin/env python3
"""Regenerate derived files from the pinned upstream nlpm checkout.

Usage:
  python tools/build.py [--upstream PATH] [--check] [--allow-drift]

Generated, never edit by hand:
  skill/references/<upstream knowledge dirs>/**
  skill/scripts/nlpm-check.py
  skill/references/INDEX.md
  UPSTREAM_FILES.txt

Everything else in skill/ is authored here and is left untouched.
"""
from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUFFIXES = {".md", ".yaml", ".yml", ".json"}
DESC_RE = re.compile(r"^description:\s*(.+)$", re.M)
UPSTREAM_URL = "https://github.com/xiaolai/nlpm"


def pin() -> str:
    return (ROOT / "UPSTREAM_PIN").read_text(encoding="utf-8").strip()


def head(up: Path) -> str | None:
    try:
        r = subprocess.run(
            ["git", "-C", str(up), "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True,
        )
        return r.stdout.strip()
    except (subprocess.SubprocessError, OSError):
        return None


def brief(text: str) -> str:
    m = DESC_RE.search(text)
    return m.group(1).strip().strip('"').strip("'") if m else ""


def build_into(up: Path, dest: Path) -> list[str]:
    src = up / "skills" / "nlpm"
    checker = up / "bin" / "nlpm-check"
    if not src.is_dir() or not checker.is_file():
        raise SystemExit(f"incomplete upstream checkout: {src} / {checker}")

    written: list[str] = []
    pairs: list[tuple[str, str]] = []

    for f in sorted(src.rglob("*")):
        if not f.is_file() or f.suffix not in SUFFIXES:
            continue
        rel = (Path("skill/references") / f.relative_to(src)).as_posix()
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, p)
        written.append(rel)
        pairs.append((rel, f.relative_to(up).as_posix()))

    rel = "skill/scripts/nlpm-check.py"
    p = dest / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(checker, p)
    written.append(rel)
    pairs.append((rel, "bin/nlpm-check"))

    ref_root = dest / "skill/references"
    index = [
        "# Knowledge index",
        "",
        "Generated by tools/build.py. Load these on demand from SKILL.md.",
        "",
    ]
    for skill_md in sorted(ref_root.glob("*/SKILL.md")):
        desc = brief(skill_md.read_text(encoding="utf-8"))
        index.append(f"- `{skill_md.parent.name}/SKILL.md` - {desc}")
    extra = sorted(ref_root.glob("*/references/*.md"))
    if extra:
        index += ["", "Scoring reference files:"]
        index += [f"- `{f.relative_to(ref_root).as_posix()}`" for f in extra]
    index += ["", "Host profile: `workbuddy.md` (authored here)", ""]
    (ref_root / "INDEX.md").write_text("\n".join(index), encoding="utf-8", newline="\n")
    written.append("skill/references/INDEX.md")

    manifest = [
        "# Generated by tools/build.py. Do not edit.",
        f"# upstream: {UPSTREAM_URL}",
        f"# commit: {pin()}",
        "# format: <path here> <- <path upstream>",
        "",
    ]
    manifest += [f"{a} <- {b}" for a, b in pairs]
    manifest.append("")
    (dest / "UPSTREAM_FILES.txt").write_text(
        "\n".join(manifest), encoding="utf-8", newline="\n"
    )
    written.append("UPSTREAM_FILES.txt")
    return written


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", default=str(ROOT / ".cache/upstream"))
    ap.add_argument("--check", action="store_true", help="compare without writing")
    ap.add_argument("--allow-drift", action="store_true", help="allow upstream HEAD != pin")
    args = ap.parse_args()

    up = Path(args.upstream).resolve()
    if not up.is_dir():
        raise SystemExit(f"upstream checkout not found: {up}\nclone: git clone {UPSTREAM_URL} {up}")

    expected = pin()
    actual = head(up)
    if actual and actual != expected and not args.allow_drift:
        raise SystemExit(
            f"upstream HEAD {actual[:8]} != pin {expected[:8]}. "
            "Check out the pinned commit or pass --allow-drift."
        )

    if args.check:
        with tempfile.TemporaryDirectory() as td:
            dest = Path(td)
            written = build_into(up, dest)
            drift = [
                rel for rel in written
                if not (ROOT / rel).is_file()
                or not filecmp.cmp(ROOT / rel, dest / rel, shallow=False)
            ]
        if drift:
            print("generated files differ; run python tools/build.py:")
            for rel in drift:
                print(f"  {rel}")
            return 1
        print(f"{len(written)} generated files match upstream {expected[:8]}")
        return 0

    written = build_into(up, ROOT)
    print(f"regenerated {len(written)} files from upstream {expected[:8]}")
    print("authored files untouched: SKILL.md / workbuddy.md / NOTICE.md / four scripts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
